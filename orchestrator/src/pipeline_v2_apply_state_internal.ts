import { deepFreezeValue } from "./pipeline_v2_freeze_internal.ts";
import { isPipelineV2SafeId, isLowercaseSha256, isNonNegativeSafeInteger, isPositiveSafeInteger } from "./pipeline_v2_scalar.ts";

/**
 * The durable journal of one project apply operation: a revisioned,
 * crash-safe state document stored at
 * `<applyStoreRoot>/operations/<applyId>/state.json` through the shared
 * revisioned snapshot-store substrate.
 *
 * Schema v2 (the filesystem-writer increment) extends the v1 preparation
 * journal with the execution statuses `applying`, `applied`, `conflict`
 * and `recovery_required`, and the single `execution` projection that
 * carries the durable per-step progress:
 *
 *   - `completed_step_count` — the dense number of plan steps durably
 *     applied (0..plan_step_count); every completed step's postcondition
 *     is verified by the recovery walk;
 *   - `active_step` — the committed temp intent of the frontier step
 *     (`{step_index, temp_name}`), non-null exactly while a temp-owning
 *     step is in flight; the name was generated by the writer and
 *     committed before the temp was created, so it is the ownership root
 *     of any temp artifact left by a crash.
 *
 * There is deliberately NO v1 migration: schema version 1 documents are
 * rejected with the established typed legacy message and never rewritten.
 * The journal never stores: raw error messages, host paths, project
 * paths, file contents, payload bytes, timestamps, operation/session ids
 * or credentials. `applied` is terminal and immutable; `conflict` is
 * terminal; `recovery_required` is soft (a retry that proves a
 * recoverable project state may continue).
 */

export const PIPELINE_V2_APPLY_STATE_KIND = "pipeline_v2_project_apply_operation";
export const PIPELINE_V2_APPLY_STATE_SCHEMA_VERSION = 2;

export const PIPELINE_V2_APPLY_OPERATION_STATUSES = [
  "preparing",
  "prepared",
  "applying",
  "applied",
  "conflict",
  "recovery_required",
  "failed",
] as const;
export type PipelineV2ApplyOperationStatus = (typeof PIPELINE_V2_APPLY_OPERATION_STATUSES)[number];

/** The statuses the filesystem writer may treat as executable. */
export const PIPELINE_V2_APPLY_EXECUTABLE_STATUSES = [
  "prepared",
  "applying",
] as const;

/** The statuses whose stored typed result the writer returns verbatim. */
export const PIPELINE_V2_APPLY_TERMINAL_RESULT_STATUSES = [
  "applied",
  "conflict",
  "recovery_required",
  "failed",
] as const;

export class PipelineV2ApplyStateError extends Error {
  declare readonly reason: "invalid_state" | "invalid_json";

  constructor(reason: "invalid_state" | "invalid_json", message: string) {
    super(message);
    this.name = "PipelineV2ApplyStateError";
    Object.defineProperty(this, "reason", {
      value: reason,
      enumerable: true,
      writable: false,
      configurable: false,
    });
  }
}

/** The durable temp intent of the frontier step. */
export interface PipelineV2ApplyActiveStep {
  readonly step_index: number;
  readonly temp_name: string;
}

/** The durable execution projection of the filesystem writer. */
export interface PipelineV2ApplyExecutionState {
  readonly completed_step_count: number;
  readonly active_step: PipelineV2ApplyActiveStep | null;
}

export interface PipelineV2ApplyOperationState {
  readonly schema_version: typeof PIPELINE_V2_APPLY_STATE_SCHEMA_VERSION;
  readonly kind: typeof PIPELINE_V2_APPLY_STATE_KIND;
  readonly revision: number;
  readonly apply_id: string;
  readonly run_id: string;
  readonly project_id: string;
  readonly observation: string;
  readonly terminal_revision: number;
  /** The opaque root-binding digest (never a host path). */
  readonly project_root_binding: string;
  /** The plan digest once the plan was published and re-read (null before). */
  readonly plan_digest: string | null;
  readonly plan_step_count: number | null;
  readonly plan_payload_count: number | null;
  readonly plan_total_payload_byte_count: number | null;
  /** The number of payload artifacts durably sealed so far. */
  readonly sealed_payload_count: number;
  readonly status: PipelineV2ApplyOperationStatus;
  /** The closed, content-free failure/refusal reason; null unless terminal-with-reason. */
  readonly failure_reason: string | null;
  /** The durable execution progress; non-null exactly for executable/terminal-executed statuses. */
  readonly execution: PipelineV2ApplyExecutionState | null;
}

function isPlainObject(value: unknown): value is Record<string, unknown> {
  return typeof value === "object" && value !== null && !Array.isArray(value);
}

function expectExactKeys(value: Record<string, unknown>, what: string, required: readonly string[]): void {
  const allowed = new Set(required);
  for (const key of required) {
    if (!Object.prototype.hasOwnProperty.call(value, key)) {
      throw new PipelineV2ApplyStateError("invalid_state", `${what} is missing the required field "${key}"`);
    }
  }
  for (const key of Object.getOwnPropertyNames(value)) {
    if (!Object.prototype.hasOwnProperty.call(value, key)) {
      continue;
    }
    if (!allowed.has(key)) {
      throw new PipelineV2ApplyStateError("invalid_state", `${what} carries an unknown field`);
    }
  }
}

function optionalDigest(value: unknown, what: string): string | null {
  if (value === null) {
    return null;
  }
  if (!isLowercaseSha256(value)) {
    throw new PipelineV2ApplyStateError("invalid_state", `${what} must be null or a lowercase 64-hex digest`);
  }
  return value;
}

function optionalCount(value: unknown, what: string): number | null {
  if (value === null) {
    return null;
  }
  if (!isNonNegativeSafeInteger(value)) {
    throw new PipelineV2ApplyStateError("invalid_state", `${what} must be null or a non-negative safe integer`);
  }
  return value;
}

const ACTIVE_STEP_TEMP_NAME_PATTERN = /^\.apply-tmp-[0-9a-f]{32}$/;

function validateExecution(raw: unknown, status: PipelineV2ApplyOperationStatus): PipelineV2ApplyExecutionState | null {
  const executable = status === "applying" || status === "applied";
  const soft = status === "recovery_required";
  const conflicted = status === "conflict";
  if (raw === null) {
    if (executable) {
      throw new PipelineV2ApplyStateError("invalid_state", `an ${status} operation state must carry its execution progress`);
    }
    return null;
  }
  if (!isPlainObject(raw)) {
    throw new PipelineV2ApplyStateError("invalid_state", "the operation state execution is not an object");
  }
  expectExactKeys(raw, "the operation state execution", ["completed_step_count", "active_step"]);
  if (!isNonNegativeSafeInteger(raw["completed_step_count"])) {
    throw new PipelineV2ApplyStateError("invalid_state", "the execution completed_step_count must be a non-negative safe integer");
  }
  const completed = raw["completed_step_count"];
  let activeStep: PipelineV2ApplyActiveStep | null = null;
  const activeRaw = raw["active_step"];
  if (activeRaw !== null) {
    if (!isPlainObject(activeRaw)) {
      throw new PipelineV2ApplyStateError("invalid_state", "the execution active_step is not an object");
    }
    expectExactKeys(activeRaw, "the execution active_step", ["step_index", "temp_name"]);
    if (!isPositiveSafeInteger(activeRaw["step_index"])) {
      throw new PipelineV2ApplyStateError("invalid_state", "the active step_index must be a positive safe integer");
    }
    const tempName = activeRaw["temp_name"];
    if (typeof tempName !== "string" || !ACTIVE_STEP_TEMP_NAME_PATTERN.test(tempName)) {
      throw new PipelineV2ApplyStateError("invalid_state", "the active step temp_name does not follow the committed temp grammar");
    }
    activeStep = deepFreezeValue({ step_index: activeRaw["step_index"] as number, temp_name: tempName });
  }
  if (status === "prepared" || status === "preparing" || status === "failed") {
    throw new PipelineV2ApplyStateError("invalid_state", `a ${status} operation state must not carry execution progress`);
  }
  if (activeStep !== null) {
    if (status !== "applying" && status !== "recovery_required") {
      throw new PipelineV2ApplyStateError("invalid_state", "only an applying or recovery-required operation state carries an active temp intent");
    }
    if (activeStep.step_index !== completed + 1) {
      throw new PipelineV2ApplyStateError("invalid_state", "the active step must be the frontier step");
    }
  }
  if (conflicted && completed !== 0) {
    throw new PipelineV2ApplyStateError("invalid_state", "a conflicted operation state cannot carry completed steps");
  }
  if (status === "applied" && activeStep !== null) {
    throw new PipelineV2ApplyStateError("invalid_state", "an applied operation state must not carry an active step");
  }
  return deepFreezeValue({ completed_step_count: completed, active_step: activeStep });
}

const APPLY_FAILURE_REASON_PATTERN = /^[a-z][a-z0-9_]{0,63}$/;

export function validateApplyOperationState(raw: unknown): PipelineV2ApplyOperationState {
  if (!isPlainObject(raw)) {
    throw new PipelineV2ApplyStateError("invalid_state", "the operation state is not an object");
  }
  if (raw["schema_version"] === 1) {
    throw new PipelineV2ApplyStateError(
      "invalid_state",
      "apply operation state schema version 1 is not supported (no migration from v1 preparation journals)",
    );
  }
  expectExactKeys(
    raw,
    "the operation state",
    [
      "schema_version",
      "kind",
      "revision",
      "apply_id",
      "run_id",
      "project_id",
      "observation",
      "terminal_revision",
      "project_root_binding",
      "plan_digest",
      "plan_step_count",
      "plan_payload_count",
      "plan_total_payload_byte_count",
      "sealed_payload_count",
      "status",
      "failure_reason",
      "execution",
    ],
  );
  if (raw["schema_version"] !== PIPELINE_V2_APPLY_STATE_SCHEMA_VERSION) {
    throw new PipelineV2ApplyStateError("invalid_state", "the operation state schema version is not supported");
  }
  if (raw["kind"] !== PIPELINE_V2_APPLY_STATE_KIND) {
    throw new PipelineV2ApplyStateError("invalid_state", "the operation state kind is not supported");
  }
  if (!isPositiveSafeInteger(raw["revision"])) {
    throw new PipelineV2ApplyStateError("invalid_state", "the operation state revision must be a positive safe integer");
  }
  for (const field of ["apply_id", "run_id", "project_id"] as const) {
    if (!isPipelineV2SafeId(raw[field])) {
      throw new PipelineV2ApplyStateError("invalid_state", `the operation state ${field} is not a safe id`);
    }
  }
  if (!isLowercaseSha256(raw["observation"])) {
    throw new PipelineV2ApplyStateError("invalid_state", "the operation state observation is not a lowercase 64-hex digest");
  }
  if (!isPositiveSafeInteger(raw["terminal_revision"])) {
    throw new PipelineV2ApplyStateError("invalid_state", "the operation state terminal_revision must be a positive safe integer");
  }
  if (!isLowercaseSha256(raw["project_root_binding"])) {
    throw new PipelineV2ApplyStateError("invalid_state", "the operation state project_root_binding is not a lowercase 64-hex digest");
  }
  const status = raw["status"];
  if (typeof status !== "string" || !(PIPELINE_V2_APPLY_OPERATION_STATUSES as readonly string[]).includes(status)) {
    throw new PipelineV2ApplyStateError("invalid_state", "the operation state status is not supported");
  }
  const statusValue = status as PipelineV2ApplyOperationStatus;
  const failureReason = raw["failure_reason"];
  if (
    failureReason !== null &&
    (typeof failureReason !== "string" || !APPLY_FAILURE_REASON_PATTERN.test(failureReason))
  ) {
    throw new PipelineV2ApplyStateError("invalid_state", "the operation state failure_reason must be null or a short reason token");
  }
  const sealedPayloadCount = raw["sealed_payload_count"];
  if (!isNonNegativeSafeInteger(sealedPayloadCount)) {
    throw new PipelineV2ApplyStateError("invalid_state", "the operation state sealed_payload_count must be a non-negative safe integer");
  }

  const reasonRequired = statusValue === "failed" || statusValue === "conflict" || statusValue === "recovery_required";
  if (reasonRequired && typeof failureReason !== "string") {
    throw new PipelineV2ApplyStateError("invalid_state", `a ${statusValue} operation state must carry its failure reason`);
  }
  if (!reasonRequired && failureReason !== null) {
    throw new PipelineV2ApplyStateError("invalid_state", "only a failed, conflicted or recovery-required operation state carries a failure reason");
  }
  const planStepCount = optionalCount(raw["plan_step_count"], "the operation state plan_step_count");
  const planPayloadCount = optionalCount(raw["plan_payload_count"], "the operation state plan_payload_count");
  if ((planStepCount === null) !== (raw["plan_digest"] === null) || (planPayloadCount === null) !== (raw["plan_digest"] === null)) {
    throw new PipelineV2ApplyStateError("invalid_state", "the plan projection fields must be present exactly when the plan digest is");
  }
  const planTotalPayloadByteCount = raw["plan_total_payload_byte_count"];
  if ((planTotalPayloadByteCount === null) !== (raw["plan_digest"] === null)) {
    throw new PipelineV2ApplyStateError("invalid_state", "the plan projection fields must be present exactly when the plan digest is");
  }
  if (planTotalPayloadByteCount !== null && !isNonNegativeSafeInteger(planTotalPayloadByteCount)) {
    throw new PipelineV2ApplyStateError("invalid_state", "the operation state plan_total_payload_byte_count must be a non-negative safe integer");
  }
  const execution = validateExecution(raw["execution"], statusValue);
  if (statusValue === "prepared" && raw["plan_digest"] === null) {
    throw new PipelineV2ApplyStateError("invalid_state", "a prepared operation state must carry its plan digest");
  }
  if ((statusValue === "applying" || statusValue === "applied" || statusValue === "conflict" || statusValue === "recovery_required") && planDigestNull(raw)) {
    throw new PipelineV2ApplyStateError("invalid_state", `an ${statusValue} operation state must carry its plan digest`);
  }
  if (statusValue === "prepared" && sealedPayloadCount !== planPayloadCount) {
    throw new PipelineV2ApplyStateError("invalid_state", "a prepared operation state must have every payload sealed");
  }
  if (execution !== null && planStepCount !== null && execution.completed_step_count > planStepCount) {
    throw new PipelineV2ApplyStateError("invalid_state", "the execution completed_step_count exceeds the plan step count");
  }
  if (statusValue === "applied" && execution !== null && planStepCount !== null && execution.completed_step_count !== planStepCount) {
    throw new PipelineV2ApplyStateError("invalid_state", "an applied operation state must carry every plan step completed");
  }
  return deepFreezeValue({
    schema_version: PIPELINE_V2_APPLY_STATE_SCHEMA_VERSION,
    kind: PIPELINE_V2_APPLY_STATE_KIND,
    revision: raw["revision"],
    apply_id: raw["apply_id"] as string,
    run_id: raw["run_id"] as string,
    project_id: raw["project_id"] as string,
    observation: raw["observation"] as string,
    terminal_revision: raw["terminal_revision"] as number,
    project_root_binding: raw["project_root_binding"],
    plan_digest: optionalDigest(raw["plan_digest"], "the operation state plan_digest"),
    plan_step_count: planStepCount,
    plan_payload_count: planPayloadCount,
    plan_total_payload_byte_count: planTotalPayloadByteCount as number | null,
    sealed_payload_count: sealedPayloadCount,
    status: statusValue,
    failure_reason: failureReason as string | null,
    execution,
  });
}

function planDigestNull(raw: Record<string, unknown>): boolean {
  return raw["plan_digest"] === null;
}

export function parseApplyOperationState(raw: string): PipelineV2ApplyOperationState {
  let parsed: unknown;
  try {
    parsed = JSON.parse(raw);
  } catch {
    throw new PipelineV2ApplyStateError("invalid_json", "the stored operation state is not valid JSON");
  }
  return validateApplyOperationState(parsed);
}
